let LANG='pt',I18N_RX=null,I18N_FIX=null;
function setLang(l){
  LANG=['en','es'].includes(l)?l:'pt';
  document.documentElement.lang=LANG==='pt'?'pt-BR':LANG;
  if(LANG==='pt')return;
  const col=LANG==='en'?1:2;
  I18N_RX=I18N_ROWS.filter(r=>r[0] instanceof RegExp).map(r=>[r[0],r[col]]);
  const fix=I18N_ROWS.filter(r=>typeof r[0]==='string').sort((a,b)=>b[0].length-a[0].length);
  I18N_FIX={map:new Map(fix.map(r=>[r[0],r[col]])),rx:new RegExp(fix.map(r=>r[0].replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('|'),'g')};
}
/* traduz um texto (também usado em canvas e lembretes) */
function tr(s){
  if(LANG==='pt'||!s||typeof s!=='string')return s;
  let o=s;
  for(const [rx,to] of I18N_RX){rx.lastIndex=0;o=o.replace(rx,to)}
  return o.replace(I18N_FIX.rx,m=>I18N_FIX.map.get(m));
}
const I18N_DONE=new WeakMap();
function trNode(n){
  if(n.nodeType===3){
    if(I18N_DONE.get(n)===n.nodeValue)return;
    const v=tr(n.nodeValue);if(v!==n.nodeValue)n.nodeValue=v;I18N_DONE.set(n,n.nodeValue);return;
  }
  if(n.nodeType!==1||n.tagName==='SCRIPT'||n.tagName==='STYLE')return;
  if(n.placeholder)n.placeholder=tr(n.placeholder);
  n.childNodes.forEach(trNode);
}
function startI18n(){
  if(LANG==='pt')return;
  trNode(document.body);
  new MutationObserver(ms=>ms.forEach(m=>{
    if(m.type==='characterData')trNode(m.target);
    else m.addedNodes.forEach(trNode);
  })).observe(document.body,{childList:true,subtree:true,characterData:true});
}
function detectLang(saved){
  if(saved)return saved;
  const n=(navigator.language||'pt').toLowerCase();
  return n.startsWith('pt')?'pt':n.startsWith('es')?'es':'en';
}
